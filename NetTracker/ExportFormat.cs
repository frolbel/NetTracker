namespace NetTracker
{
    /// <summary>
    /// Поддерживаемые форматы экспорта данных перехваченных сетевых соединений.
    /// </summary>
    public enum ExportFormat
    {
        /// <summary>
        /// Простая текстовая таблица (как при выводе в консоль). Формат по умолчанию.
        /// </summary>
        Raw,

        /// <summary>
        /// Файл значений, разделённых точкой с запятой (;), подходящий для Excel.
        /// </summary>
        Csv,

        /// <summary>
        /// Структурированный массив объектов в формате JSON.
        /// </summary>
        Json,

        /// <summary>
        /// Текстовый файл в формате файла hosts (IP-адрес и DNS-имя), разделённые табуляцией.
        /// Исключает дубликаты и неизвестные домены.
        /// </summary>
        Host,

        /// <summary>
        /// Текстовый файл в формате файла hosts (IP-адрес и DNS-имя), разделённые табуляцией и
        /// реальные IP-адреса заменяются на 127.0.0.1.
        /// </summary>
        /// <remarks>
        /// Удобен для создания правил блокировки (blacklists).
        /// </remarks>
        Dummy
    }
}
