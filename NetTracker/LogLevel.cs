namespace NetTracker
{
    /// <summary>
    /// Уровни детализации вывода в консоль.
    /// </summary>
    /// <remarks>
    /// Определяют, какие категории сообщений будут отображаться пользователю.
    /// </remarks>
    public enum LogLevel
    {
        /// <summary>
        /// Только критические ошибки, препятствующие работе программы (например, отказ в доступе, ошибки записи файла).
        /// </summary>
        Error = 0,
        
        /// <summary>
        /// Предупреждения о нештатных, но не критичных ситуациях (например, неверный формат аргумента или использование настроек по умолчанию).
        /// </summary>
        Warning = 1,

        /// <summary>
        /// Основные данные захвата: строки таблицы с перехваченными сетевыми соединениями.
        /// </summary>
        Capture = 2,

        /// <summary>
        /// Выводит статистику по перехваченным данным.
        /// </summary>
        Statistics = 3,

        /// <summary>
        /// Информационные сообщения о ходе работы программы (запуск мониторинга, статусы импорта/экспорта).
        /// </summary>
        Info = 4,

        /// <summary>
        /// Отладочная информация, поясняющая внутренние состояния и процессы. Уровень вывода по умолчанию.
        /// </summary>
        Debug = 5,

        /// <summary>
        /// Максимальная детализация: вывод первичных необработанных данных, событий ETW на низком уровне (трассировка).
        /// </summary>
        Trace = 6
    }
}
